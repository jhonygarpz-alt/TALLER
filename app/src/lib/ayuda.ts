const quitar = (s: string) => s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase()
export const clave = (s: string) => quitar(s).replace(/[^a-zñ ]+/g, ' ').replace(/\s+/g, ' ').trim()

const MAPA = new Map<string, string>()
for (const [k, v] of Object.entries(A)) MAPA.set(clave(k), v)

/** Reglas para textos que cambian (folios, fechas…). */
const REGLAS: [RegExp, string][] = [
  [/^ot-?\d+/i, 'Orden de trabajo: da clic para abrir su expediente (datos, presupuesto, trabajos, costos y entrega).'],
  [/^bienvenid/i, 'Resumen general del taller del periodo seleccionado. Cambia el periodo con el selector de la derecha.'],
  [/^oc-?\d+/i, 'Orden de compra: da clic para ver sus partidas, autorizarla o recibirla.'],
]

export function buscarAyuda(texto: string): string | null {
  const t = texto.trim()
  if (!t) return null
  for (const [re, txt] of REGLAS) if (re.test(t)) return txt
  return MAPA.get(clave(t)) ?? null
}
